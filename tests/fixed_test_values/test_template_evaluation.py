"""
Regression tests: verify every template's output matches the stored snapshot.

Reference fixtures live in ``tests/fixtures/templates/*.npz`` (one per
template) and are generated by running::

    python tests/fixtures/generate_reference.py

Each fixture stores ``N_SAMPLES`` parameter draws together with the
corresponding template outputs; this test re-evaluates every draw and
checks the result against the stored value.

Re-generate only when a change to a template is *intentional*.
"""

import pathlib
import unittest

import jax
import jax.numpy as jnp
import numpy as np
import numpy.testing as npt

from gwb_templates.template import get_template_from_registry

jax.config.update("jax_enable_x64", True)


_FIXTURES_DIR = pathlib.Path(__file__).parent / "reference_templates"

# Templates that use numpy/scipy internally and expect np.ndarray inputs.
_NUMPY_TEMPLATES = frozenset(
    {
        "cosmic_string_model_i",
        "cosmic_string_model_i_edf",
        "cosmic_string_model_i_eos",
        "cosmic_string_model_ii",
        "abelian_higgs_model_ii",
    }
)


def _make_test(name: str, fixture_path: pathlib.Path):
    use_numpy = name in _NUMPY_TEMPLATES

    def test_method(self: "TestTemplateEvaluation") -> None:
        data = np.load(str(fixture_path))
        fvec = jnp.array(data["fvec"]) if use_numpy else jnp.array(data["fvec"])
        pars_all = data["pars"]  # (N_SAMPLES, N_PARAMS)
        outputs_all = data["outputs"]  # (N_SAMPLES, N_FREQ)
        model = get_template_from_registry(name)
        for j in range(len(pars_all)):
            p = np.array(pars_all[j]) if use_numpy else jnp.array(pars_all[j])
            out = np.asarray(model.omega_gw_h2(fvec, *p))
            npt.assert_allclose(
                out,
                outputs_all[j],
                rtol=1e-5,
                atol=1e-13,
                err_msg=f"Template '{name}' sample {j} differs from stored reference.",
            )

    test_method.__name__ = f"test_{name}"
    return test_method


class TestTemplateEvaluation(unittest.TestCase):
    """One test per template; each checks N_SAMPLES parameter draws."""


for _fixture in sorted(_FIXTURES_DIR.glob("*.npz")):
    _name = _fixture.stem
    setattr(TestTemplateEvaluation, f"test_{_name}", _make_test(_name, _fixture))


if __name__ == "__main__":
    unittest.main(verbosity=2)
